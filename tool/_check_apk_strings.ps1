$ErrorActionPreference = 'Stop'
$root = 'D:\JOB\mind_kepper\mind_keeper'
$apk = Join-Path $root 'build\app\outputs\flutter-apk\app-debug.apk'
$bytes = [System.IO.File]::ReadAllBytes($apk)
$text = [System.Text.Encoding]::UTF8.GetString($bytes)

# Build patterns from code points so the console codepage cannot corrupt them.
function P([int[]]$cp) { -join ($cp | ForEach-Object { [char]$_ }) }

$patterns = @(
  @{ Name = 'Chu de ngau nhien (Viet)'; Cp = @(0x43,0x68,0x1EE7,0x20,0x0111,0x1EBF,0x20,0x6E,0x67,0x1EAA,0x75,0x20,0x6E,0x68,0x69,0x65,0x6E) },
  @{ Name = 'Custom topic';            Cp = @(0x43,0x75,0x73,0x74,0x6F,0x6D,0x20,0x74,0x6F,0x70,0x69,0x63) },
  @{ Name = 'Lesson mode';             Cp = @(0x4C,0x65,0x73,0x73,0x6F,0x6E,0x20,0x6D,0x6F,0x64,0x65) },
  @{ Name = 'Chu de tuy chinh';        Cp = @(0x43,0x68,0x1EE7,0x20,0x0111,0x1EE3,0x20,0x74,0x00FA,0x79,0x20,0x63,0x68,0x1EE9,0x6E,0x68) },
  @{ Name = 'AI Lessons (en)';         Cp = @(0x41,0x49,0x20,0x4C,0x65,0x73,0x73,0x6F,0x6E,0x73) },
  @{ Name = 'ngau nhien (mojibake)';   Cp = @(0x6E,0x67,0x1EC1,0x75,0x20,0x6E,0x68,0x69,0x65,0x6E) },
  @{ Name = 'Suggested topic (en)';    Cp = @(0x53,0x75,0x67,0x67,0x65,0x73,0x74,0x65,0x64,0x20,0x74,0x6F,0x70,0x69,0x63) }
)

foreach ($p in $patterns) {
  $s = P $p.Cp
  Write-Output ("{0,-28} => {1}" -f $p.Name, $text.Contains($s))
}

# Count U+FFFD occurrences in the APK string pool
$fffd = [char]0xFFFD
$cnt = ([regex]::Matches($text, [regex]::Escape($fffd))).Count
Write-Output ("U+FFFD in APK bytes: {0}" -f $cnt)
